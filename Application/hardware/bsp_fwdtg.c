/**
 * @file    bsp_fwdtg.c
 * @brief   看门狗驱动 — 片内 FWDGT + 外置 SGM706 双重保护
 *
 * 本文件实现车载控制器的看门狗保护方案：
 * - 片内看门狗（GD32 FWDGT）：内部硬件定时器，配置后必须定期喂狗，否则系统复位
 * - 外置看门狗（SGM706）：通过 GPIO PE1 输出脉冲，脉冲停止则外置看门狗不复位
 *
 * 双重保护配合使用：片内看门狗防止程序死锁，外置看门狗防止系统断电。
 *
 * 【固定区】以下 API 函数签名不建议修改，供 FreeRTOS 任务或定时器调用。
 */

#include "bsp_fwdtg.h"

/* ============================================================
 * 【自定义区】外置看门狗超时时间配置
 * ============================================================
 * SGM706 的典型超时时间为 1.6 秒，要求在此时间内持续输出脉冲（GPIO 翻转）。
 * 如果脉冲停止超过 1.6 秒，SGM706 将触发系统复位。
 */
#define HardWatchdogTime  1      /* 片内 FWDGT 超时时间（秒），SGM706 需 GPIO 脉冲维持 */

/* ============================================================
 * 【固定区】内部时钟频率定义
 * ============================================================
 * GD32 FWDGT 使用内部低速 RC 振荡器 IRC40K（40KHz）作为时钟源。
 * 该时钟独立于系统主时钟，即使系统主时钟失效，看门狗仍能正常工作。
 */
#define IRC 40000       /* 内部 RC 振荡器频率：40KHz */

/* ============================================================
 * 搭建步骤 1：Set_FwdtgTime — 片内看门狗定时器配置
 * ============================================================
 * 【搭建步骤】
 *   1. 计算重装载值：reload = time_s * IRC / 256
 *      - time_s：期望的超时时间（秒）
 *      - IRC：内部 RC 振荡器频率 40KHz
 *      - 256：分频系数 FWDGT_PSC_DIV256
 *   2. 检查重装载值是否超过 4095（12 位计数器最大值）
 *      - 如果超过则截断为 4095
 *   3. 调用 fwdgt_config() 配置 FWDGT
 *
 * 【运行时步骤】
 *   1. 调用此函数时传入期望的超时秒数
 *   2. fwdgt_config() 内部设置预分频器和重装载寄存器
 *   3. 配置完成后，FWDGT 计数器按分频后的时钟递减
 *
 * 【固定区】此函数为配置函数，接口固定，建议不要修改。
 *   IRC 时钟源固定为 40KHz，FWDGT_PSC_DIV256 为固定的 256 分频。
 *
 * 【公式】超时时间计算：
 *   超时时间 = 重装载值 × 分频系数 / IRC
 *            = reload × 256 / 40000
 *   最大超时时间 = 4095 × 256 / 40000 ≈ 26.2 秒
 *
 * @param time_s  期望的超时时间（秒），最大约 26 秒
 */
void Set_FwdtgTime(uint16_t time_s)
{
    /* 计算重装载值：
     * 公式：reload = time × IRC / 分频系数
     * 以 time=1s 为例：reload = 1 × 40000 / 256 ≈ 156
     */
    uint16_t reload = time_s * IRC / 256;

    /* 【固定区】FWDGT 计数器为 12 位，最大重装载值 4095 */
    if (reload > 4095)
        reload = 4095;

    /* config FWDGT counter clock: 40KHz(IRC40K) / 256 = 156.25 Hz */
    fwdgt_config(reload, FWDGT_PSC_DIV256);
}

/* ============================================================
 * 搭建步骤 2：Bsp_fwdtgInit — 片内看门狗初始化 + 外置看门狗 GPIO 配置
 * ============================================================
 * 【搭建步骤】
 *   1. 配置 GPIO PE1 为推挽输出模式（外置看门狗 SGM706 的喂狗信号引脚）
 *   2. 调用 Set_FwdtgTime() 配置片内看门狗定时器
 *   3. 调用 Fwdtg_enabale() 使能片内看门狗
 *
 * 【运行时步骤】
 *   1. 系统启动后尽早调用此函数
 *   2. GPIO PE1 初始化为输出，准备输出翻转信号
 *   3. FWDGT 配置完成后立即使能，开始倒计时
 *   4. 必须在超时前调用 Feed_Fwdtg() 喂狗
 *
 * 【固定区】GPIO PE1 是外置看门狗的固定引脚，不可更改。
 *   初始化顺序固定：GPIO → FWDGT 配置 → FWDGT 使能。
 */
void Bsp_fwdtgInit(void)
{
    /* ---- 外置看门狗信号 GPIO PE1 ---- */
    /* 配置 PE1 为推挽输出，50MHz 速度，无上下拉 */
    gpio_mode_set(GPIOE, GPIO_MODE_OUTPUT, GPIO_PUPD_NONE, GPIO_PIN_1);
    gpio_output_options_set(GPIOE, GPIO_OTYPE_PP, GPIO_OSPEED_50MHZ, GPIO_PIN_1);

    /* 配置并使能片内 FWDGT */
    Set_FwdtgTime(HardWatchdogTime);
    Fwdtg_enabale();
}

/* ============================================================
 * 搭建步骤 3：Fwdtg_enabale — 片内看门狗使能
 * ============================================================
 * 【搭建步骤】
 *   1. 先重装载计数器（写入键寄存器序列）
 *   2. 再使能 FWDGT
 *
 * 【运行时步骤】
 *   1. fwdgt_counter_reload() — 将重装载值写入计数器
 *   2. fwdgt_enable() — 使能 FWDGT，开始倒计时
 *
 * 【固定区】使能顺序不可颠倒，必须 reload 后再 enable。
 *   注意：FWDGT 使能后无法关闭（除非系统复位），
 *   因此配置必须在使能之前完成。
 */
void Fwdtg_enabale(void)
{
    fwdgt_counter_reload();
    fwdgt_enable();
}

/* ============================================================
 * 运行时步骤 4：Feed_Fwdtg — 喂狗函数
 * ============================================================
 * 【运行时步骤】
 *   1. GPIO PE1 电平翻转 → 向外置 SGM706 输出脉冲，维持其不超时
 *   2. fwdgt_counter_reload() → 重装载片内 FWDGT 计数器，防止片内看门狗超时复位
 *
 * 【自定义区】喂狗频率取决于 HardWatchdogTime 的设置。
 *   建议喂狗周期不超过超时时间的一半（例如超时 1 秒则每 500ms 喂狗一次）。
 *
 * 外置看门狗（SGM706）的喂狗机制：
 *   - SGM706 通过检测 GPIO PE1 的脉冲来判定系统是否正常运行
 *   - 每次 GPIO 翻转（高→低 或 低→高）都会复位 SGM706 的内部定时器
 *   - 如果脉冲停止超过 1.6 秒，SGM706 触发系统复位
 *   - 因此：PE1 必须持续输出高低电平交替的脉冲信号
 *
 * 片内看门狗（GD32 FWDGT）的喂狗机制：
 *   - FWDGT 是一个递减计数器
 *   - fwdgt_counter_reload() 将计数器重置为预设的重装载值
 *   - 如果计数器减到 0 前没有 reload，系统复位
 */
void Feed_Fwdtg(void)
{
    /* GPIO PE1 翻转：产生脉冲维持外置看门狗 */
    gpio_bit_toggle(GPIOE, GPIO_PIN_1);

    /* 重装载片内 FWDGT 计数器 */
    fwdgt_counter_reload();
}

/* ============================================================
 * 搭建步骤 5：Bsp_fwdtgInit_hw — 仅初始化外置看门狗 GPIO
 * ============================================================
 * 【搭建步骤】
 *   仅配置 GPIO PE1，不涉及片内 FWDGT
 *
 * 适用场景：只需要外置看门狗保护，不需要片内看门狗时使用。
 *   例如：系统中已有其他机制处理程序死锁，仅需 SGM706 防止系统断电。
 */
void Bsp_fwdtgInit_hw(void)
{
    /* 外置看门狗信号 GPIO PE1 */
    gpio_mode_set(GPIOE, GPIO_MODE_OUTPUT, GPIO_PUPD_NONE, GPIO_PIN_1);
    gpio_output_options_set(GPIOE, GPIO_OTYPE_PP, GPIO_OSPEED_50MHZ, GPIO_PIN_1);
}

/* ============================================================
 * 运行时步骤 6：Feed_Fwdtg_hw — 仅喂外置看门狗
 * ============================================================
 * 【运行时步骤】
 *   仅翻转 GPIO PE1，不重装载 FWDGT
 *
 * 适用场景：与 Bsp_fwdtgInit_hw 配套使用，只需为 SGM706 提供脉冲。
 */
void Feed_Fwdtg_hw(void)
{
    /* 仅翻转 GPIO PE1 产生脉冲，维持外置看门狗 */
    gpio_bit_toggle(GPIOE, GPIO_PIN_1);
}
