/**
 * @file    bsp_uart.h
 * @brief   UART 驱动头文件 — 带注释学习版
 *
 * =============================================================================
 * 三路 UART 速查：
 *   UART0 ── RS232 ── PB13(TX) / PB14(RX) ── 上位机/调试终端
 *   UART1 ── RS485 ── PB15(TX) / PD8(RX)  ── 工业外设通信
 *   UART2 ── TTL   ── PA5(TX) / PA6(RX)   ── 子芯片通信（预留）
 * =============================================================================
 */

#ifndef _BSP_UART_H_
#define _BSP_UART_H_

#include "include.h"

/* ============================================================
 * 【自定义区】常用波特率定义
 * ============================================================ */
#define UART_BAUD_9600    9600
#define UART_BAUD_19200   19200
#define UART_BAUD_57600   57600
#define UART_BAUD_115200  115200

/* ============================================================
 * 公共 API 函数声明
 * ============================================================ */

/**
 * BSP UART 初始化入口
 * 调用位置：main.c 中 BSP 外设初始化阶段（Step 7）
 * 内部初始化：互斥量 + UART0/UART1/UART2 + DMA
 *
 * 【自定义区】根据需要取消注释对应初始化调用（见 bsp_uart.c）
 */
void Bsp_UartInit(void);

/**
 * UART 轮询发送（互斥量保护）
 *
 * 参数：
 *   usart_periph ── USART0 / USART1 / USART2
 *   pdata        ── 待发送数据指针
 *   Lens         ── 数据长度（字节数）
 *
 * 说明：
 *   使用互斥量保护，同一时刻只有一个任务能使用对应 UART。
 *   每个字节发送后等待 TC 标志，确保数据真正发完才返回。
 *
 * 【自定义区】适用于小数据量发送（< 100 字节）
 *   大数据量建议使用 uart_dma_send()
 */
void Uart_SendData(uint32_t usart_periph, uint8_t *pdata, uint16_t Lens);

/**
 * UART DMA 发送（加速版）
 *
 * 参数：
 *   txbuf ── 待发送数据指针
 *   len   ── 数据长度（自动限制 ≤ 2048 字节）
 *
 * 说明：
 *   - 使用 DMA 控制器自动发送，不占用 CPU
 *   - 自动等待上一帧 DMA 发送完成（最多 4ms）
 *   - 适用于大数据量或高频率发送场景
 *
 * 【自定义区】适用于：
 *   - 固件升级数据（大量数据）
 *   - 日志高速输出
 *   - 高速传感器数据透传
 */
void uart_dma_send(uint8_t* txbuf, uint16_t len);

#endif /* _BSP_UART_H_ */
