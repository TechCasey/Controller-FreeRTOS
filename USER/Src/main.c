/**
 * @file    main.c
 * @brief   入口函数 — 学习版
 *
 * =============================================================================
 * 程序运行流程（按步骤执行，顺序固定，不要随意调整）
 * =============================================================================
 * 硬件上电后，CPU 从 Reset_Handler 开始执行，跳转到 main()，
 * 按以下步骤完成所有初始化，最后启动 FreeRTOS 调度器。
 *
 * ⚠️ 重要：Step 4.8 __enable_irq() 之前不能启动调度器！
 * ⚠️ 重要：Step 4.7 创建所有任务/队列/定时器/信号量之后才能启动调度器！
 *
 * =============================================================================
 * Step 1  — NVIC 优先级分组配置
 * Step 2  — GPIO 时钟使能（所有 GPIO Port A~F）
 * Step 3  — 调试外设配置
 * Step 4  — SysTick 初始化（FreeRTOS 心跳基准）
 * Step 5  — SEGGER RTT 初始化（调试打印通道）
 * Step 6  — 关闭全局中断（__disable_irq），准备初始化外设
 * Step 7  — BSP 外设初始化（CAN/UART/Timer/ADC/GPIO/PWM/SPI/I2C/Flash）
 * Step 8  — 外部存储初始化（W25Qxx Flash / EEPROM）
 * Step 9  — 系统参数从 Flash 加载
 * Step 10 — 雷达/传感器初始化
 * Step 11 — FreeRTOS 运行时间统计定时器初始化（Timer7，50µs 周期）
 * Step 12 — ⚠️【核心自定义区】所有 RTOS 资源创建：任务 / 队列 / 定时器 / 信号量
 * Step 13 — 打开全局中断（__enable_irq）
 * Step 14 — 启动 FreeRTOS 调度器（vTaskStartScheduler）
 * Step 15 — 调度器接管后永不返回，以下循环不会执行
 * =============================================================================
 */

#include "main.h"
#include "include.h"

/* ============================================================
 * 全局变量
 * ============================================================ */
/* CAN 通信模块全局实例（定义在 CanComm.c） */
extern CanComm_t s_CanComm;

/* ============================================================
 * Step 2 — GPIO 时钟使能（所有端口）
 * ============================================================ */
static void enable_gpio_rcu(void)
{
    rcu_periph_clock_enable(RCU_GPIOA);
    rcu_periph_clock_enable(RCU_GPIOB);
    rcu_periph_clock_enable(RCU_GPIOC);
    rcu_periph_clock_enable(RCU_GPIOD);
    rcu_periph_clock_enable(RCU_GPIOE);
    rcu_periph_clock_enable(RCU_GPIOF);
}

/* ============================================================
 * Step 3 — 调试外设配置（保持 JTAG/SWO 在调试时可用）
 * ============================================================ */
static void debug_cfg(void)
{
    /* 在 deepsleep 模式下保持调试外设连接 */
    dbg_periph_enable(DBG_FWDGT_HOLD);
    dbg_periph_enable(DBG_WWDGT_HOLD);
    dbg_periph_enable(DBG_TIMER0_HOLD);
    dbg_periph_enable(DBG_TIMER1_HOLD);
    dbg_periph_enable(DBG_I2C0_HOLD);
    dbg_periph_enable(DBG_I2C1_HOLD);
    dbg_periph_enable(DBG_TIMER7_HOLD);
    dbg_periph_enable(DBG_TIMER5_HOLD);
    dbg_periph_enable(DBG_TIMER6_HOLD);
    dbg_periph_enable(DBG_MFCOM_HOLD);
    dbg_periph_enable(DBG_CAN0_HOLD);
    dbg_periph_enable(DBG_CAN1_HOLD);
    dbg_periph_enable(DBG_TIMER20_HOLD);
    dbg_periph_enable(DBG_TIMER19_HOLD);
}

/* ============================================================
 * Step 15 — 永远不会执行到的安全网（调度器接管后永不返回）
 * ============================================================ */
void _never_called_(void)
{
    while (1) {
        /* 调度器启动后不会执行到这里 */
    }
}

/* ============================================================
 * Step 1 + Step 4 ~ Step 13 — 主函数入口
 * ============================================================ */
int main(void)
{
    /* ---------------------------------------------------------------
     * Step 1 — NVIC 优先级分组
     * ---------------------------------------------------------------
     * NVIC_PRIGROUP_PRE4_SUB0：
     *   4 位用于抢占优先级（PRE），0 位用于子优先级（SUB）
     *   即全部 16 级优先级都是抢占优先级，没有子优先级分组
     * --------------------------------------------------------------- */
    nvic_priority_group_set(NVIC_PRIGROUP_PRE4_SUB0);

    /* ---------------------------------------------------------------
     * Step 2 — GPIO 时钟使能
     * --------------------------------------------------------------- */
    enable_gpio_rcu();

    /* ---------------------------------------------------------------
     * Step 3 — 调试外设配置
     * --------------------------------------------------------------- */
    debug_cfg();

    /* ---------------------------------------------------------------
     * Step 4 — SysTick 初始化（FreeRTOS 心跳定时器）
     * ---------------------------------------------------------------
     * SysTick_Init() 设置 SysTick 每 1ms 中断一次（configTICK_RATE_HZ=1000）
     * 这是 FreeRTOS 调度器的"心跳"：
     *   - vTaskDelay() 依赖此心跳工作
     *   - 软件定时器依赖此心跳工作
     *   - 任务调度依赖此心跳切换任务
     * --------------------------------------------------------------- */
    SysTick_Init();

    /* ---------------------------------------------------------------
     * Step 5 — SEGGER RTT 初始化
     * ---------------------------------------------------------------
     * RTT（Real Time Transfer）是 SEGGER 提供的调试通道，
     * 通过 J-Link 在调试时实时打印数据，不需要额外的 UART 线。
     * SEGGER_RTT_Init() 必须先于所有 printf 调用执行。
     * --------------------------------------------------------------- */
    SEGGER_RTT_Init();
    /* SEGGER_SYSVIEW_Conf();  // SystemView 追踪（可选） */

    /* ---------------------------------------------------------------
     * Step 6 — 关闭全局中断
     * ---------------------------------------------------------------
     * 在初始化 BSP 外设期间关闭所有中断，
     * 防止外设初始化过程中触发意外的中断。
     * Step 13 __enable_irq() 之后再打开。
     * --------------------------------------------------------------- */
    __disable_irq();

    /* ---------------------------------------------------------------
     * Step 7 — BSP 外设初始化
     * ---------------------------------------------------------------
     * CAN0/CAN1：车载总线通信
     * Timer5/6/7/20：系统定时器、输入捕获、运行时间统计
     * ADC：模拟量采集（电压/电流/传感器）
     * GPIO：LED、按键、开关量输入输出
     * PWM：电机驱动输出
     * SPI：外部 Flash 通信
     * I2C：EEPROM 通信
     * --------------------------------------------------------------- */
    CAN0_Init(CAN_250K_BPS);
    CAN1_Init(CAN_250K_BPS);
    Bsp_TimerInit();
    Bsp_adcInit();
    Bsp_GPIO_Init();
    Bsp_PwmInit();

    /* ---------------------------------------------------------------
     * Step 8 — 外部 Flash 初始化（W25Qxx，littlefs 文件系统）
     * --------------------------------------------------------------- */
    w25q_lfs_init();

    /* ---------------------------------------------------------------
     * Step 9 — EEPROM 初始化
     * --------------------------------------------------------------- */
    eeprom_init();

    /* ---------------------------------------------------------------
     * Step 10 — 系统参数从 Flash 加载
     * ---------------------------------------------------------------
     * 从 Flash 读取保存的作业参数（行数、播种量、施肥量等），
     * 加载到 s_sysParam 结构体中。
     * --------------------------------------------------------------- */
    SystemParamInit();

    /* ---------------------------------------------------------------
     * Step 11 — 雷达/传感器初始化
     * --------------------------------------------------------------- */
    Radar_Init();

    /* ---------------------------------------------------------------
     * Step 12 — ⚠️【核心自定义区】所有 RTOS 资源创建
     * ---------------------------------------------------------------
     * ⚠️ 重要：所有 RTOS 资源（任务/队列/定时器/信号量）
     * 必须在这里创建完毕，然后才能启动调度器！
     *
     * 创建顺序建议：
     *   1. 创建消息队列（xQueueCreate）
     *   2. 创建信号量（xSemaphoreCreateBinary/Mutex）
     *   3. 创建任务（xTaskCreate）—— 任务函数开始运行
     *   4. 在任务内或主函数中创建定时器（xTimerCreate）
     *   5. 启动定时器（xTimerStart）
     *
     * 下面的示例展示了标准的任务初始化调用顺序：
     * --------------------------------------------------------------- */

    /* CAN 通信任务初始化（接收任务 + 发送任务 + 队列 + 定时器 + 信号量） */
    CanTaskInit();

    /* 简单示例任务初始化 */
    SimpleTaskInit();

    /* ---------------------------------------------------------------
     * Step 13 — 打开全局中断
     * ---------------------------------------------------------------
     * 所有外设初始化完成，现在打开中断响应。
     * 之后 CAN 中断、TIMER 中断等可以正常触发。
     * --------------------------------------------------------------- */
    __enable_irq();

    /* ---------------------------------------------------------------
     * Step 14 — 启动 FreeRTOS 调度器
     * ---------------------------------------------------------------
     * vTaskStartScheduler() 是 FreeRTOS 的启动函数：
     *   1. 创建 Idle 任务（优先级为 0）
     *   2. 创建 Timer Daemon 任务（如果 configUSE_TIMERS=1）
     *   3. 配置 PendSV 和 SVC 中断
     *   4. 启动 SysTick（如果尚未启动）
     *   5. 切换到最高优先级就绪任务
     *
     * 此函数不会返回，之后 CPU 完全由 FreeRTOS 调度器控制。
     * --------------------------------------------------------------- */
    vTaskStartScheduler();

    /* ---------------------------------------------------------------
     * Step 15 — 永远不会执行到这里
     * ---------------------------------------------------------------
     * vTaskStartScheduler() 成功启动后，CPU 控制权完全交给调度器。
     * 如果程序走到了这里，说明调度器启动失败（通常是 heap 不足）。
     * --------------------------------------------------------------- */
    _never_called_();
}